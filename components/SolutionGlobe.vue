// (3199:8782), holding "The_Solution" (3201:7987). Both states of it are drawn
// side by side in 3237:8038.
//
// Figma draws the graphic as 3,447 individual vector dots: one per land cell of a
// perspective-projected globe, each a 2–3px ellipse, each foreshortened by where
// it sits on the sphere. Shipped as drawn that is 810 KB of SVG and 3,447 DOM
// nodes — the wrong shape twice over, because the brief for this graphic is that
// it ANIMATES, per dot, while the reader scrolls a run of phrases past it.
//
// So the geometry is extracted to numbers ahead of time (data/solutionGlobe.ts,
// generated by scripts/extract-globe-dots.py) and drawn to a canvas. That is the
// whole reason for the canvas: with the field as three typed arrays, any dot can
// be moved, scaled, lit or dimmed for the cost of arithmetic, and the entire field
// is a handful of fill calls per frame. 27 KB of data, one element, no DOM writes
// while the reader scrolls.
//
// It is the same division of labour as the home page's particle cluster: geometry
// is pure data, the component owns only the CLOCK-to-pixels step, and the things
// driving it are numbers the section passes in.
//
// TWO numbers and a switch, and the split between them is the point of this piece
// rather than an implementation detail — three kinds of time, named:
//
//   wake     the wave. TRIGGERED, not scrubbed — it runs on a clock the section
//            starts the moment the pinned stage comes to rest, and plays out at
//            its own pace whatever the reader does next. A wave read off scroll
//            position is not a wave: it stops when the reader stops, runs
//            backwards when they scroll back, and the faster they read the faster
//            it breaks. This one is an event with a beginning and an end.
//   t        the scroll through the held stretch, and the departure is ALL it is
//            used for. See EXIT_FROM — leaving is a fact about where the page has
//            got to, not about the wave, so it stays on the scroll.
