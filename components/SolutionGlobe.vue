/** Per-dot constants, derived once: where the cell falls in the wave's order, and
 *  its own breathing phase and rate. Kept as arrays beside the geometry so the
 *  frame loop reads flat memory and allocates nothing. */
const wakeAt = new Float32Array(field.count)
const breathPhase = new Float32Array(field.count)
const breathRate = new Float32Array(field.count)

{
    // A cheap deterministic hash per index — same field on every load, and no
    // 3,447-entry random table to ship.
    const hash = (i: number, salt: number) => {
        const v = Math.sin((i + 1) * salt) * 43758.5453
        return v - Math.floor(v)
    }
    for (let i = 0; i < field.count; i++) {
        // West to east, with a southward lean and a per-cell scatter: the front
        // arrives as a ragged diagonal, like a terminator line, rather than as a
        // vertical bar.
        //
        // The scatter is SMALL — a fiftieth of the crossing against a crest band
        // a quarter of it wide — and that ratio is the difference between a wave
        // and a mess. Neighbouring cells have to be at nearly the same point of
        // the throw or the band is a spray of dots at every height rather than
        // one ridge lifting; at 0.05 the dense parts of the map (Brazil, the
        // eastern seaboard) turned to noise the moment JUMP was worth looking at.
        const west = field.x[i] / GLOBE_FIELD.width
        const south = field.y[i] / GLOBE_FIELD.height
        wakeAt[i] = west * 0.88 + south * 0.1 + hash(i, 12.9898) * 0.02
        breathPhase[i] = hash(i, 78.233) * Math.PI * 2
        breathRate[i] = BREATH_MS[0] + hash(i, 45.164) * (BREATH_MS[1] - BREATH_MS[0])
    }
}

/** WHICH cells are thrown: every other one down each column of the lattice.
 *
 *  The light is untouched by this — the wave's colour still crosses all 3,447
 *  cells, because Figma's two states are the whole map before and the whole map
 *  after, and a field that lit in stripes would simply be wrong at the end. Only
 *  the THROW is thinned. With every cell lifted there is nothing left at rest for
 *  the displacement to be read against, and a band of map that moves together
 *  reads as the map moving; leaving every other cell where it was gives the thrown
 *  ones something to be measured by, and the throw then reads as dots jumping out
 *  of the field rather than as the field flexing.
 *
 *  Which cells those are is a fact about the drawn lattice rather than about the
 *  motion, and finding them is not free — see utils/globeColumns.ts, which is also
 *  why it is not done here. */
const moves = columnParity(field)

function smoothstep(edge0: number, edge1: number, x: number) {
    const u = Math.min(1, Math.max(0, (x - edge0) / (edge1 - edge0)))
    return u * u * (3 - 2 * u)
}

/** The front's position in the field's own units. Widened by the edge at both
 *  ends so that wake 0 leaves every cell untouched and wake 1 has the front clear
 *  of the last of them — and it is the front rather than the wake that everything
 *  below is written against, because the trail reads at fronts the wave has
 *  already been past. */
function frontAt(wake: number) {
    return wake * (1 + WAKE_EDGE * 2) - WAKE_EDGE
}

/** How far through its throw a cell is with the front here: 0 before it arrives,
 *  1 once it has gone. Broken out of `dotState` for the trail, which asks for it
 *  at moments the cell has already left. */
function wokenAt(i: number, front: number) {
    return smoothstep(wakeAt[i] - WAKE_EDGE, wakeAt[i] + WAKE_EDGE, front)
}

/** Peaks at half-woken, zero at both ends: the cell is on the front exactly once,
 *  and everything that makes the wave a wave hangs off this. */
function crestOf(woken: number) {
    return woken * (1 - woken) * 4
}

/** The per-dot animation, and the ONLY place it lives.
 *
 *  @param i       the cell's index into the field
 *  @param front   the front's position, from `frontAt`
 *  @param clockMs ambient wall time, ms — stopped when the piece is off screen or
 *                 paused, so it is motion time rather than elapsed time
 *  @returns       drawn-pixel offset, a scale on the cell's own radii, and `ink`:
 *                 a position on the ramp, 0 idle, 1 lit, 2 crest.
 */
function dotState(i: number, front: number, clockMs: number) {
    const woken = wokenAt(i, front)
    const crest = crestOf(woken)
    const breath = 1 + BREATH * woken * Math.sin((clockMs / breathRate[i]) * Math.PI * 2 + breathPhase[i])

    // The throw — and only the throw — is every other cell down the column; see
    // `moves`. The ink below is the whole field, front and all.
    const thrown = moves[i] ? crest : 0

    return {
        dy: -JUMP * thrown,
        scale: 1 + CREST_GROW * thrown,
        ink: Math.min(2, woken * breath + crest)
    }
}

/** The beacon pool. Instance state, unlike everything above it: a beacon is a
 *  position in a loop rather than a fact about the field, and two of these
 *  graphics on one page would each need their own. Fixed length and reused for
 *  ever — a beacon that has finished is the same object with a new cell under it,
 *  so starting and ending one costs nothing. */
interface Beacon {
    /** The cell it stands on. */
    dot: number
    /** What its card says, picked with the cell. Held even when the cards are off,
     *  so a beacon that starts on the second group and finishes on the third has
     *  something to show rather than picking a symbol mid-flight. */
    pair: string
    /** ms into its own run: negative while it waits its turn, PARKED while the
     *  beacons are switched off. */
    at: number
}
/** Not running and not waiting to. Distinct from a negative `at`, which is a
 *  beacon counting down to its next run. */
const PARKED = Number.NEGATIVE_INFINITY
const beaconPool: Beacon[] = Array.from({ length: BEACON_COUNT }, () => ({
    dot: 0,
    pair: CARD_PAIRS[0],
    at: PARKED
}))

/** How long one run lasts, which is the same question as "is there a card on the
 *  end of it". Read every frame rather than stored, so a reader crossing from one
 *  group to the next changes what the lights already in the air are doing. */
function beaconLife() {
    return (
        BEACON_SPARK_MS +
        BEACON_CLIMB_MS +
        (loopingCards() ? CARD_HOLD_AT_ROOF_MS : 0) +
        BEACON_CATCH_MS +
        BEACON_FADE_MS
    )
}

function beaconRest(life: number) {
    return life * (BEACON_REST[0] + Math.random() * (BEACON_REST[1] - BEACON_REST[0]))
}

function beaconWake(b: Beacon) {
    b.dot = (Math.random() * field.count) | 0
    b.pair = CARD_PAIRS[(Math.random() * CARD_PAIRS.length) | 0]
}

/** Advance the pool. `delta` is the frame's own motion time, so the beacons stop
 *  with everything else when the piece is off screen and pick up where they were
 *  rather than jumping — same reasoning as `clockMs`.
 *
 *  Which cells they use is `Math.random`, and deliberately not the deterministic
 *  hash the rest of the file runs on. That hash exists so the FIELD is the same
 *  picture on every load; a beacon is not part of the picture, it is something
 *  passing through it, and a loop that plays the same lights in the
 *  same order every time is a loop the reader can see the end of. */
function stepBeacons(delta: number) {
    const life = beaconLife()

    // The destination, up or down. Not a beacon and not on any beacon's clock —
    // one transition, held for as long as the group is on stage.
    hubLit = Math.min(1, Math.max(0, hubLit + (delta / HUB_LIGHT_MS) * (loopingRoutes() ? 1 : -1)))

    for (const b of beaconPool) {
        if (b.at === PARKED) {
            if (!looping()) continue
            // Waking the pool. The first run is spread over a whole rest
            // period, or the entire pool leaves the map on the same frame.
            beaconWake(b)
            b.at = -Math.random() * life * BEACON_REST[1]
            continue
        }

        // Switched off. A beacon still counting down to its turn has nothing to
        // finish, so it parks here rather than launching a light two seconds into
        // the next group's copy; one already in the air is the only case worth
        // playing out, and it does that below.
        if (!looping() && b.at < 0) {
            b.at = PARKED
            continue
        }

        b.at += delta
        if (b.at < life) continue

        // Done. Another cell, or park it — it is the RESPAWN that the switch
        // stops, which is what lets a light in the air finish its run instead of
        // being cut off mid-climb.
        if (!looping()) {
            b.at = PARKED
            continue
        }
        beaconWake(b)
        b.at = -beaconRest(life)
    }
}

/** One beacon's frame, or null when there is nothing of it to draw.
 *
 *  `head` and `tail` are HEIGHTS above the cell in drawn px, not coordinates —
 *  the drawing turns them into a line. `lit` is how much of the cell's own colour
 *  has gone over to the beacon, and `fade` is the light going out at the end.
 *
 *  The two easings are the two halves of the gesture and are not interchangeable:
 *  the head leaves fast and decelerates into the roof (ease-out, so it arrives
 *  rather than stops), while the tail sets off gently and arrives gently
 *  (smoothstep), which is what makes the catch-up read as the trail being drawn
 *  in after the light rather than as a second light chasing it. */
function beaconState(at: number, show: number) {
    if (at < 0 || at >= beaconLife()) return null

    const spark = Math.min(1, at / BEACON_SPARK_MS)

    const climbMs = at - BEACON_SPARK_MS
    const u = Math.min(1, Math.max(0, climbMs / BEACON_CLIMB_MS))
    const head = BEACON_ROOF * (1 - (1 - u) ** 3)

    // `show` is the card's whole turn, inserted here — zero where there is no
    // card, so the light goes straight from arriving to being caught up.
    const catchMs = climbMs - BEACON_CLIMB_MS - show
    const c = Math.min(1, Math.max(0, catchMs / BEACON_CATCH_MS))
    const tail = BEACON_ROOF * c * c * (3 - 2 * c)

    const fadeMs = catchMs - BEACON_CATCH_MS
    const fade = 1 - Math.min(1, Math.max(0, fadeMs / BEACON_FADE_MS))

    // The cell holds its colour for as long as the trail is still standing on it,
    // and lets go as the trail lifts away.
    return { lit: spark * (1 - c), head, tail, fade }
}

/** And the card's own frame, measured from the moment the light stopped climbing.
 *  Null until there is one and after it has gone.
 *
 *  Each stage is a plain ramp against its own span and they do not overlap, which
 *  is what the three drawn states are: the bubble, then the container, then the
 *  letters. `chars` is a count rather than a fraction because a letter is either
 *  typed or it is not. */
function cardState(at: number) {
    // The lead: the card's own clock starts before the light gets there.
    const ms = at - BEACON_SPARK_MS - BEACON_CLIMB_MS + CARD_LEAD_MS
    if (ms < 0) return null

    const exit = Math.min(1, Math.max(0, (ms - CARD_SHOW_MS) / CARD_EXIT_MS))
    if (exit >= 1) return null

    const typeFrom = CARD_DOT_MS + CARD_BOX_MS

    return {
        dot: Math.min(1, ms / CARD_DOT_MS),
        box: Math.min(1, Math.max(0, (ms - CARD_DOT_MS) / CARD_BOX_MS)),
        // Ease-in-out on the pair, which is a curve on the SPEED of the typing:
        // the first letter or two arrive unhurried, the middle of the string goes
        // quickly, and the last letter settles instead of being cut off. Linear,
        // a six-letter string at this length reads as a machine emitting
        // characters at a fixed rate — true, and the wrong kind of true.
        typed: smoothstep(typeFrom, typeFrom + CARD_TYPE_MS, ms),
        // Ease-out on the lift, so it leaves the way the light arrived.
        lift: CARD_EXIT_LIFT * (1 - (1 - exit) ** 3),
        alpha: 1 - exit
    }
}

/** One route's frame, measured from the moment its card finished typing. Null
 *  before the money leaves and after it has gone.
 *
 *  `head` and `tail` are positions ALONG the arc, 0 at the card and 1 at the hub,
 *  which is the same shape as the lights: the tail sits at the card while the head
 *  runs (so the trail is the whole of the path taken, exactly as Figma draws it),
 *  and only then does the tail follow it home.
 *
 *  Ease-in-out on both, because this one is a journey rather than a launch — it
 *  leaves, it travels, it arrives. The lights use an ease-OUT for their climb,
 *  which is the shape of a thing thrown. */
function routeState(at: number) {
    const ms = at - BEACON_SPARK_MS - BEACON_CLIMB_MS + CARD_LEAD_MS - ROUTE_FROM_MS
    if (ms < 0) return null

    const fadeMs = ms - ROUTE_FLY_MS - ROUTE_CATCH_MS
    const fade = 1 - Math.min(1, Math.max(0, fadeMs / ROUTE_FADE_MS))
    if (fade <= 0) return null

    return {
        head: smoothstep(0, ROUTE_FLY_MS, ms),
        tail: smoothstep(ROUTE_FLY_MS, ROUTE_FLY_MS + ROUTE_CATCH_MS, ms),
        fade
    }
}

/** The pill, as a path. Always fully rounded — the radius IS half the height, so
 *  this is two arcs and two lines rather than a rounded rectangle with a corner
 *  radius that has to be clamped. At the 24-wide state the two arcs meet and it is
 *  a circle, which is what Figma's state 01 is. */
function pillPath(x: number, y: number, w: number, h: number) {
    const r = h / 2
    const path = new Path2D()
    path.moveTo(x + r, y)
    path.lineTo(x + w - r, y)
    path.arc(x + w - r, y + r, r, -Math.PI / 2, Math.PI / 2)
    path.lineTo(x + r, y + h)
    path.arc(x + r, y + r, r, Math.PI / 2, -Math.PI / 2)
    path.closePath()
    return path
}

// ------------------------------------------------------------------ renderer --
// Cells are batched by quantised ink: one Path2D per bucket, one fill per bucket.
// The alternative — set a fill style and fill per cell — is 3,447 state changes a
// frame. Twenty-four steps across a ramp whose two ends differ by 34 points of red
// is under three points a step, which is invisible on a 2px dot and turns the
// whole field into at most twenty-four fills.
//
// The trail does NOT get that treatment. Its ghosts need an alpha the ink ramp
// cannot carry, and under that alpha the ramp stops being worth carrying, so they
// are three flat fills — one per lag, in the crest's colour — rather than three
// more rows of buckets. See the note in `draw`.
//
// The departure stays outside all of it: it applies to every cell equally, so it
// is a factor on the alpha of each fill rather than an axis of its own.
const BUCKETS = 24

/** The ramp, resolved to fill strings once. Index b is ink `b / (BUCKETS - 1) * 2`
 *  — idle at 0, lit at the midpoint, crest at the top. */
const RAMP = (() => {
    const rgb = (hex: string) => [0, 2, 4].map((at) => parseInt(hex.slice(1 + at, 3 + at), 16))
    const stops = [rgb(IDLE_INK), rgb(LIT_INK), rgb(CREST_INK)]
    const out: string[] = []
    for (let b = 0; b < BUCKETS; b++) {
        const v = (b / (BUCKETS - 1)) * 2
        const lo = v <= 1 ? 0 : 1
        const u = v - lo
        const mix = (c: number) => Math.round(stops[lo][c] + (stops[lo + 1][c] - stops[lo][c]) * u)
        out.push(`rgb(${mix(0)}, ${mix(1)}, ${mix(2)})`)
    }
    return out
})()

let ctx: CanvasRenderingContext2D | null = null
let cssWidth = 0
let cssHeight = 0
let scale = 1
let rafId = 0
let lastFrame = 0
/** Ambient time, accumulated only while the piece is on screen and running — so
 *  scrolling away and back resumes the breathing instead of snapping it to a new
 *  phase. Same reasoning as the particle cluster's `motionMs`. */
let clockMs = 0
let onScreen = false
let reduced = false
let io: IntersectionObserver | null = null
let ro: ResizeObserver | null = null

function draw() {
    if (!ctx || cssWidth <= 0) return

    ctx.clearRect(0, 0, cssWidth, cssHeight)

    const t = Math.min(1, Math.max(0, props.t))
    const present = 1 - smoothstep(EXIT_FROM, EXIT_TO, t)
    if (present <= 0.01) return

    // The field is scaled by WIDTH against the drawn 760 frame, then centred in
    // whatever height the box has. At the drawn square this is pixel-exact to
    // Figma; at a shorter box it keeps the field's size and loses only air.
    const k = cssWidth / BOX
    const originX = FIELD_X * k
    const originY = (cssHeight - GLOBE_FIELD.height * k) / 2 + FIELD_BIAS_Y * k

    // The field, by ink bucket, and the trail: ONE path per lag, not a row of
    // buckets per lag. A ghost is drawn at two fifths of the alpha or less, which
    // flattens the ramp to nothing — the twenty-four inks are within a couple of
    // points of each other by the time they land on the ground — so bucketing the
    // ghosts would be three more rows of fills to carry a distinction that cannot
    // be seen. Three fills, one per lag, and the ink is a constant.
    const paths: (Path2D | null)[] = new Array(BUCKETS).fill(null)
    const trails: (Path2D | null)[] = new Array(TRAIL_STEPS + 1).fill(null)
    const wake = Math.min(1, Math.max(0, props.wake))
    const front = frontAt(wake)

    /** One cell into one path. Everything drawn goes through here — the cell and
     *  every ghost of it — so the moveTo below is written once. */
    const plot = (path: Path2D, i: number, cy: number, grow: number) => {
        const cx = originX + field.x[i] * k
        const rx = Math.max(0.35, field.rx[i] * grow * k)
        const ry = Math.max(0.35, field.ry[i] * grow * k)
        // The moveTo is not optional. `ellipse` on a path that already has a
        // subpath joins the two with a straight line, so a bucket of 200 cells
        // without it draws 199 hairlines across the map — which looks exactly like
        // a smear. Landing the pen on the arc's own start point (angle 0, i.e.
        // cx + rx) makes that joining line zero-length.
        path.moveTo(cx + rx, cy)
        path.ellipse(cx, cy, rx, ry, 0, 0, Math.PI * 2)
    }

    for (let i = 0; i < field.count; i++) {
        const state = dotState(i, front, clockMs)
        const bucket = Math.min(BUCKETS - 1, Math.max(0, Math.round((state.ink / 2) * (BUCKETS - 1))))
        plot(
            paths[bucket] || (paths[bucket] = new Path2D()),
            i,
            originY + (field.y[i] + state.dy) * k,
            state.scale
        )

        // The trail, and only where there is something to trail: a cell that is
        // not thrown has not moved, one the front has not reached has nothing
        // behind it, and one it left more than a trail ago has nothing left. Those
        // two comparisons are what keep the extra work on the front band instead
        // of on the field.
        if (!moves[i]) continue
        if (front <= wakeAt[i] - WAKE_EDGE) continue
        if (front - TRAIL_STEPS * TRAIL_LAG >= wakeAt[i] + WAKE_EDGE) continue

        for (let s = 1; s <= TRAIL_STEPS; s++) {
            const crest = crestOf(wokenAt(i, front - s * TRAIL_LAG))
            // Under a fiftieth of the throw the ghost is inside the cell it is
            // trailing, where all it would do is thicken a resting dot.
            if (crest < 0.02) continue
            plot(
                trails[s] || (trails[s] = new Path2D()),
                i,
                originY + (field.y[i] - JUMP * crest) * k,
                (1 + CREST_GROW * crest) * (1 - TRAIL_TAPER * s)
            )
        }
    }

    // Oldest ghost first, then the field over the top: a trail is behind the thing
    // making it. All three are the crest's own colour — a ghost is a copy of the
    // cell at its brightest — and the fade is entirely in the alpha.
    ctx.fillStyle = CREST_INK
    for (let s = TRAIL_STEPS; s >= 1; s--) {
        const path = trails[s]
        if (!path) continue
        ctx.globalAlpha = present * TRAIL_ALPHA * (1 - (s - 1) / TRAIL_STEPS)
        ctx.fill(path)
    }

    ctx.globalAlpha = present
    for (let b = 0; b < BUCKETS; b++) {
        const path = paths[b]
        if (!path) continue
        ctx.fillStyle = RAMP[b]
        ctx.fill(path)
    }

    // The beacons last, over everything: they are lights, and the field is what
    // they are leaving. A 2px line with round caps IS the drawn pill, so each one
    // is a stroke and a fill — a dozen or so of each at the busiest, against the
    // field's 3,447 cells, which is why they are drawn one at a time instead of
    // being batched into the machinery above.
    const show = loopingCards() ? CARD_HOLD_AT_ROOF_MS : 0
    ctx.lineCap = 'round'
    ctx.lineWidth = BEACON_WIDTH * k
    for (const beacon of beaconPool) {
        const state = beaconState(beacon.at, show)
        if (!state) continue

        const i = beacon.dot
        const x = originX + field.x[i] * k
        const foot = originY + field.y[i] * k

        if (state.lit > 0.01) {
            ctx.globalAlpha = present * state.lit
            ctx.fillStyle = BEACON_INK
            ctx.beginPath()
            ctx.ellipse(
                x,
                foot,
                Math.max(0.35, field.rx[i] * k),
                Math.max(0.35, field.ry[i] * k),
                0,
                0,
                Math.PI * 2
            )
            ctx.fill()
        }

        if (state.fade <= 0.01) continue
        const head = foot - state.head * k
        const tail = foot - state.tail * k
        // A gradient needs two places to run between, and at the end of the catch
        // there is only one — what is left there is the head itself.
        if (tail - head > 0.5) {
            const ramp = ctx.createLinearGradient(x, head, x, tail)
            ramp.addColorStop(0, BEACON_INK)
            ramp.addColorStop(1, BEACON_GONE)
            ctx.strokeStyle = ramp
        } else {
            ctx.strokeStyle = BEACON_INK
        }
        ctx.globalAlpha = present * state.fade
        ctx.beginPath()
        ctx.moveTo(x, head)
        ctx.lineTo(x, tail)
        ctx.stroke()
    }

    // The destination, under everything that arrives at it.
    if (hubLit > 0.01) {
        const hx = originX + field.x[hubDot] * k
        const hy = originY + field.y[hubDot] * k
        ctx.globalAlpha = present * hubLit
        ctx.fillStyle = HUB_RING_INK
        ctx.beginPath()
        ctx.arc(hx, hy, (field.rx[hubDot] + HUB_RING) * k, 0, Math.PI * 2)
        ctx.fill()
        ctx.fillStyle = ROUTE_INK
        ctx.beginPath()
        ctx.ellipse(
            hx,
            hy,
            Math.max(0.35, field.rx[hubDot] * k),
            Math.max(0.35, field.ry[hubDot] * k),
            0,
            0,
            Math.PI * 2
        )
        ctx.fill()
    }

    if (loopingCards()) drawCards(originX, originY, k, present)
    // Routes ride the destination's own light rather than the switch: leaving the
    // group takes the hub down over HUB_LIGHT_MS and the money still in the air
    // goes with it, instead of a dozen arcs being cut off mid-flight.
    if (hubLit > 0.01) drawRoutes(originX, originY, k, present * hubLit)

    ctx.globalAlpha = 1
}

/** The profit routes, last of all — over the cards, which is the order Figma
 *  draws them in (the route vectors are the animation frame's last children) and
 *  the right one: a route passes in FRONT of the trades it is not leaving from,
 *  so the eye follows it home instead of losing it under a pill.
 *
 *  `present` arrives already multiplied by the destination's own light, so this
 *  draws nothing the reader can see once the hub has gone dark. */
function drawRoutes(originX: number, originY: number, k: number, present: number) {
    if (!ctx) return

    const hx = field.x[hubDot]
    const hy = field.y[hubDot]
    ctx.lineCap = 'round'
    ctx.lineJoin = 'round'
    ctx.lineWidth = ROUTE_WIDTH * k

    for (const beacon of beaconPool) {
        const route = routeState(beacon.at)
        if (!route) continue

        // From the card's centre-top: its bottom sits on the light's roof, so its
        // top is one card higher again.
        const i = beacon.dot
        const x0 = field.x[i]
        const y0 = field.y[i] - BEACON_ROOF - CARD_H
        const dx = hx - x0
        const dy = hy - y0
        const chord = Math.hypot(dx, dy)
        // A card standing on the destination has nowhere to send anything.
        if (chord < 12) continue

        // The arc: one control point, straight up from the middle of the chord by
        // twice the apex height — a quadratic passes half way to its handle.
        const lift = Math.max(ROUTE_LIFT_MIN, ROUTE_LIFT_FRAC * chord)
        const cxDrawn = (x0 + hx) / 2
        const cyDrawn = (y0 + hy) / 2 - lift * 2

        // The piece of it that is currently lit, as its own quadratic: de
        // Casteljau at the tail, then at the head. Exact, and one curve to stroke
        // rather than a polyline to sample.
        const t0 = route.tail
        const t1 = route.head
        const qx = (t: number) =>
            (1 - t) * (1 - t) * x0 + 2 * (1 - t) * t * cxDrawn + t * t * hx
        const qy = (t: number) =>
            (1 - t) * (1 - t) * y0 + 2 * (1 - t) * t * cyDrawn + t * t * hy
        const ax = x0 + (cxDrawn - x0) * t0
        const ay = y0 + (cyDrawn - y0) * t0
        const bx = cxDrawn + (hx - cxDrawn) * t0
        const by = cyDrawn + (hy - cyDrawn) * t0

        const sx = originX + qx(t0) * k
        const sy = originY + qy(t0) * k
        const ex = originX + qx(t1) * k
        const ey = originY + qy(t1) * k
        const mx = originX + (ax + (bx - ax) * t1) * k
        const my = originY + (ay + (by - ay) * t1) * k

        // Transparent at the tail, full at the head — the gradient IS the trail,
        // and its axis is the straight line between the two ends, which is how
        // Figma's own is set up.
        if (Math.hypot(ex - sx, ey - sy) > 0.5) {
            const ramp = ctx.createLinearGradient(sx, sy, ex, ey)
            ramp.addColorStop(0, ROUTE_GONE)
            ramp.addColorStop(1, ROUTE_INK)
            ctx.strokeStyle = ramp
        } else {
            ctx.strokeStyle = ROUTE_INK
        }

        ctx.globalAlpha = present * route.fade
        ctx.beginPath()
        ctx.moveTo(sx, sy)
        ctx.quadraticCurveTo(mx, my, ex, ey)
        ctx.stroke()
    }
}

/** The trade cards, in a pass of their own after every light has been drawn.
 *
 *  Two reasons it is a second loop rather than the tail of the first: a card must
 *  sit over every beam and not just its own — one loop would let a later beam draw
 *  across an earlier card — and the text settings (font, tracking, baseline) are
 *  set once here instead of being restored around each stroke. */
function drawCards(originX: number, originY: number, k: number, present: number) {
    if (!ctx) return

    ctx.font = CARD_FONT_FACE.replace('%', String(CARD_FONT_PX * k))
    // Tracking is a recent addition to canvas; where it is missing the pair is a
    // hair tighter and, because the box is measured from the text, its pill comes
    // out a hair shorter with it. Nothing to guard.
    ctx.letterSpacing = `${CARD_TRACKING * k}px`
    ctx.textAlign = 'left'
    // Figma centres this type on its cap height (text-box-trim); canvas centres it
    // on the em box, which sits it a fraction lower. Under a pixel at 10px, and the
    // alternative is measuring cap height per frame.
    ctx.textBaseline = 'middle'
    ctx.lineWidth = CARD_STROKE_W * k

    for (const beacon of beaconPool) {
        const card = cardState(beacon.at)
        if (!card) continue

        const i = beacon.dot
        // The card's box, in drawn px: it grows with the text and is measured off
        // it, so the pill is the right size for whatever the font actually did.
        const text = beacon.pair.slice(0, Math.round(card.typed * beacon.pair.length))
        const textW = text ? ctx.measureText(text).width / k : 0
        const w = text ? CARD_PAD * 2 + CARD_BUBBLE + CARD_GAP + textW : CARD_PAD * 2 + CARD_BUBBLE

        // Centred on the beam, standing on its head, lifting as it leaves.
        const cx = originX + field.x[i] * k
        const bottom = originY + (field.y[i] - BEACON_ROOF - card.lift) * k
        const left = cx - (w / 2) * k
        const top = bottom - CARD_H * k

        const alpha = present * card.alpha

        // 2 — the container. Figma strokes it inside, so the path is inset by half
        // the stroke; drawn at the full box even while the text is still arriving,
        // which is what makes the growth read as the pill stretching.
        if (card.box > 0.01) {
            const inset = (CARD_STROKE_W * k) / 2
            const pill = pillPath(
                left + inset,
                top + inset,
                w * k - inset * 2,
                CARD_H * k - inset * 2
            )
            ctx.globalAlpha = alpha * card.box
            ctx.fillStyle = CARD_FILL
            ctx.fill(pill)
            ctx.strokeStyle = CARD_STROKE
            ctx.stroke(pill)
        }

        // 1 — the bubble, and the ring it sits in.
        const bx = left + (CARD_PAD + CARD_BUBBLE / 2) * k
        const by = top + (CARD_H / 2) * k
        ctx.globalAlpha = alpha * card.dot
        ctx.fillStyle = CARD_RING_INK
        ctx.beginPath()
        ctx.arc(bx, by, (CARD_BUBBLE / 2 + CARD_RING) * k, 0, Math.PI * 2)
        ctx.fill()
        ctx.fillStyle = CARD_BUBBLE_INK
        ctx.beginPath()
        ctx.arc(bx, by, (CARD_BUBBLE / 2) * k, 0, Math.PI * 2)
        ctx.fill()

        // 3 — the pair, as far as it has been typed. No fade on the letters: they
        // arrive, they do not appear.
        if (!text) continue
        ctx.globalAlpha = alpha
        ctx.fillStyle = CARD_TEXT_INK
        ctx.fillText(text, left + (CARD_PAD + CARD_BUBBLE + CARD_GAP) * k, by)
    }
}

function frame(now: number) {
    // Clamp the delta: a backgrounded tab hands back a multi-second gap on
    // return, which would jump the breathing and skip a beacon's whole run rather
    // than continue them.
    const delta = lastFrame ? Math.min(now - lastFrame, 64) : 0
    lastFrame = now
    clockMs += delta
    stepBeacons(delta)
    draw()
    rafId = requestAnimationFrame(frame)
}

function stop() {
    if (rafId) cancelAnimationFrame(rafId)
    rafId = 0
    lastFrame = 0
}

/** Run the ambient loop only when it can be seen and has not been paused.
 *  Everything else redraws on demand — see the props watcher. */
function sync() {
    if (onScreen && !props.paused && !reduced) {
        if (!rafId) rafId = requestAnimationFrame(frame)
    } else {
        stop()
    }
}

function resize() {
    const el = canvasRef.value
    const box = root.value
    if (!el || !box) return
    const rect = box.getBoundingClientRect()
    if (rect.width <= 0) return
    // Capped at 2: past that the extra pixels are invisible on a 2px dot and the
    // fill cost is real.
    const dpr = Math.min(2, window.devicePixelRatio || 1)
    cssWidth = rect.width
    cssHeight = rect.height
    scale = dpr
    el.width = Math.round(cssWidth * dpr)
    el.height = Math.round(cssHeight * dpr)
    el.style.width = `${cssWidth}px`
    el.style.height = `${cssHeight}px`
    ctx = el.getContext('2d')
    // One transform, so everything downstream works in CSS pixels.
    ctx?.setTransform(scale, 0, 0, scale, 0, 0)
    draw()
}

// The wave and the departure both move without the ambient loop's help — the
// first has its own clock, the second is the reader's scrolling — and when that
// loop is stopped (off screen, paused, or reduced motion) nothing else would
// repaint. While it IS running these are no-ops the next frame absorbs.
watch(
    () => [props.t, props.wake],
    () => {
        if (!rafId) draw()
    }
)
watch(() => props.paused, sync)

onMounted(() => {
    reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches
    resize()

    // Canvas text does not pull a webfont in the way a DOM node does, so ask for
    // the card's face by hand. Until it lands the cards would be drawn — and,
    // worse, MEASURED — in the fallback; the redraw is for the case where the
    // piece is sitting still when it arrives.
    document.fonts
        ?.load(CARD_FONT_FACE.replace('%', String(CARD_FONT_PX)))
        .then(() => {
            if (!rafId) draw()
        })
        .catch(() => {})

    ro = new ResizeObserver(resize)
    if (root.value) ro.observe(root.value)

    if (reduced) {
        // Resolved, once: the field lit and still. The section pins `wake` at 1
        // in this mode, so this draw is the end state.
        draw()
        return
    }

    io = new IntersectionObserver(
        (entries) => {
            for (const entry of entries) onScreen = entry.isIntersecting
            sync()
        },
        { rootMargin: '200px 0px' }
    )
    io.observe(root.value!)
})

onBeforeUnmount(() => {
    stop()
    io?.disconnect()
    ro?.disconnect()
    io = null
    ro = null
})
</script>

