/** The cell the routes come home to: the nearest one to the drawn convergence
 *  point. */
const hubDot = (() => {
    let best = 0
    let bestD = Infinity
    for (let i = 0; i < field.count; i++) {
        const dx = field.x[i] - ROUTE_HUB_AT[0]
        const dy = field.y[i] - ROUTE_HUB_AT[1]
        const d = dx * dx + dy * dy
        if (d < bestD) {
            bestD = d
            best = i
        }
    }
    return best
})()

